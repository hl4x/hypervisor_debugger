void scratch_test(void)
{
    __asm__ volatile ("int3");

    printf("IDT handled the software interrupt successfully!\n");

    uint8_t* mem = (uint8_t*)bump_alloc(0x10);
    printf("Got memory from bump allocator: 0x%p\n", (uint64_t)mem);
    for (uint8_t i =0; i < 0x10; i++) {
        mem[i] = 0xff;
    }
    memset(mem, 0x41, 10);
    for (size_t i = 0; i < 16; i++)
        printf("%02x ", mem[i]);
    printf("\n");
}

void kernel_main(multiboot_info_t *mb)
{
    init64(mb);
    //print_banner();
    //scratch_test();
    printf("\nDebugger initialized...!\n\n");

    svm_host_t host = {
        .hsave = bump_alloc_aligned(FOUR_K, FOUR_K),
        .vmsave = bump_alloc_aligned(FOUR_K, FOUR_K),
        .iopm = bump_alloc_aligned(FOUR_K * 3, FOUR_K),
        .msrpm = bump_alloc_aligned(FOUR_K * 2, FOUR_K),
    };
    svm_host_init(&host);
    svm_enable(&host);

    vcpu_t vcpu = { 0 };
    multiboot_module_t *guest_mod = boot_module_get(0);
    uint64_t guest_entry = guest_mod->mod_start;
    uint64_t *guest_stack_bottom = bump_alloc_aligned(FOUR_K, FOUR_K);
    uint64_t guest_stack_top = (uint64_t) guest_stack_bottom + FOUR_K;
    svm_vcpu_init(&vcpu, &host, (uint64_t)guest_entry,
                  (uint64_t)guest_stack_top, read_cr3(),
                  host.has_nrips);

    // main vmrun loop
    for (;;) {
        svm_vmrun(&vcpu);
        svm_handle_exit(&vcpu);
    }

    for (;;) {
        __asm__ volatile ("hlt");
    }
}
